package config;

/**
 * Стенд, на котором идёт прогон. Выбирается ключом {@code -DdeviceHost}.
 * <p>
 * Стенд — это параметр запуска, а не часть теста: сценарий на всех трёх одинаковый,
 * меняется только то, куда уходит сессия и откуда берётся приложение.
 */
public enum DeviceHost {

    /** Устройство в облаке BrowserStack App Automate. Приложение заранее загружено туда. */
    BROWSERSTACK,

    /** Эмулятор на своей машине. Устройство выбирается по имени AVD из Device Manager. */
    EMULATION,

    /** Реальный телефон, подключённый к своей машине по USB. Выбирается по серийнику из adb. */
    REAL
}
